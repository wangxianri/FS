let currentLocale = 'zh-CN'

function setLocale(locale) {
  if (translations[locale]) currentLocale = locale
}

function t(key, params) {
  const table = translations[currentLocale] || translations['zh-CN']
  let s = table[key]
  if (s === undefined) s = translations['zh-CN'][key] !== undefined ? translations['zh-CN'][key] : key
  if (params) {
    for (const k in params) {
      s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), params[k])
    }
  }
  return s
}

module.exports = { t, setLocale, translations }
