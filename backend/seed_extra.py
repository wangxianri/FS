def upsert_check_items():
    inserted = 0
    skipped = 0
    for it in CHECK_ITEMS:
        row = cur.execute(
            "SELECT id FROM fs_check_items WHERE code=%s AND name=%s",
            (it["code"], it["name"])
        )
        # 检查是否存在
        cur.execute(
            "SELECT id FROM fs_check_items WHERE code=%s AND name=%s",
            (it["code"], it["name"])
        )
        exist = cur.fetchone()
        if exist:
            skipped += 1
            continue
        cur.execute(
            "INSERT INTO fs_check_items(code,name,area,how,std,basis,penalty,fix,period,level,veto,days,role) "
            "VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
            (it["code"], it["name"], it["area"], it["how"], it["std"],
             it["basis"], it["penalty"], it["fix"], it["period"], it["level"],
             it["veto"], it["days"], it["role"])
        )
        inserted += 1
    print(f"[check_items] inserted={inserted}, skipped={skipped}, total={len(CHECK_ITEMS)}")


